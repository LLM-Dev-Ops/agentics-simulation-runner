/**
 * Database Integration Adapter
 *
 * Implements the integration adapter for database connections.
 * Supports PostgreSQL, MySQL, and other SQL databases with
 * query execution, parameterized queries, and transaction support.
 *
 * @module core/adapters/database-adapter
 * @see SPARC_ARCHITECTURE.md MOD-008 - Integration Adapter Manager
 */

import { v4 as uuidv4 } from 'uuid';

import type {
  UUID,
  DurationMs,
  ISO8601Timestamp,
  IntegrationId,
  IsolationLevel,
} from '../../types/common.js';

import type { IntegrationCallMetrics } from '../integration-call-result.js';

import {
  BaseAdapter,
  type AdapterConnection,
  type AdapterRequest,
  type AdapterResponse,
  type BaseConnectionConfig,
  type ResolvedCredentials,
  type ConnectionStatus,
} from './base-adapter.js';

// =============================================================================
// Database Adapter Types
// =============================================================================

/**
 * Supported database types
 */
export type DatabaseType = 'postgresql' | 'mysql' | 'sqlite' | 'mssql' | 'oracle';

/**
 * Database-specific connection configuration
 */
export interface DatabaseConnectionConfig extends BaseConnectionConfig {
  /**
   * Database type
   */
  readonly databaseType: DatabaseType;

  /**
   * Database host
   */
  readonly host: string;

  /**
   * Database port
   */
  readonly port: number;

  /**
   * Database name
   */
  readonly database: string;

  /**
   * Schema name (for PostgreSQL)
   */
  readonly schema?: string;

  /**
   * SSL configuration
   */
  readonly ssl?: {
    readonly enabled: boolean;
    readonly rejectUnauthorized?: boolean;
    readonly ca?: string;
    readonly cert?: string;
    readonly key?: string;
  };

  /**
   * Connection pool settings
   */
  readonly pool?: {
    readonly min?: number;
    readonly max?: number;
    readonly idleTimeoutMs?: DurationMs;
    readonly acquireTimeoutMs?: DurationMs;
  };

  /**
   * Default isolation level for transactions
   */
  readonly defaultIsolationLevel?: IsolationLevel;

  /**
   * Statement timeout in milliseconds
   */
  readonly statementTimeoutMs?: DurationMs;

  /**
   * Whether to use prepared statements
   */
  readonly usePreparedStatements?: boolean;
}

/**
 * Database operation types
 */
export type DatabaseOperation =
  | 'query'
  | 'execute'
  | 'transaction'
  | 'batch'
  | 'call'; // stored procedure

/**
 * Query parameters (positional or named)
 */
export type QueryParameters = unknown[] | Record<string, unknown>;

/**
 * Database query request
 */
export interface DatabaseQueryRequest {
  /**
   * SQL query or statement
   */
  readonly sql: string;

  /**
   * Query parameters
   */
  readonly parameters?: QueryParameters;

  /**
   * Operation type
   */
  readonly operation: DatabaseOperation;

  /**
   * Whether this is a read-only query
   */
  readonly readOnly?: boolean;

  /**
   * Fetch size for result sets
   */
  readonly fetchSize?: number;

  /**
   * Maximum rows to return
   */
  readonly maxRows?: number;
}

/**
 * Transaction options
 */
export interface TransactionOptions {
  /**
   * Isolation level for the transaction
   */
  readonly isolationLevel?: IsolationLevel;

  /**
   * Whether the transaction is read-only
   */
  readonly readOnly?: boolean;

  /**
   * Transaction timeout in milliseconds
   */
  readonly timeoutMs?: DurationMs;
}

/**
 * Database query result
 */
export interface DatabaseQueryResult {
  /**
   * Result rows (for SELECT queries)
   */
  readonly rows: Record<string, unknown>[];

  /**
   * Number of rows affected (for INSERT/UPDATE/DELETE)
   */
  readonly rowCount: number;

  /**
   * Column metadata
   */
  readonly columns?: ColumnMetadata[];

  /**
   * Last inserted ID (if applicable)
   */
  readonly lastInsertId?: string | number;

  /**
   * Warnings generated by the query
   */
  readonly warnings?: string[];

  /**
   * Query execution plan (if EXPLAIN was used)
   */
  readonly executionPlan?: unknown;
}

/**
 * Column metadata
 */
export interface ColumnMetadata {
  readonly name: string;
  readonly type: string;
  readonly nullable: boolean;
  readonly primaryKey?: boolean;
  readonly autoIncrement?: boolean;
  readonly maxLength?: number;
  readonly precision?: number;
  readonly scale?: number;
}

/**
 * Transaction handle for multi-statement transactions
 */
export interface DatabaseTransaction {
  /**
   * Transaction ID
   */
  readonly transactionId: UUID;

  /**
   * Execute a query within the transaction
   */
  query(sql: string, parameters?: QueryParameters): Promise<DatabaseQueryResult>;

  /**
   * Execute a statement within the transaction
   */
  execute(sql: string, parameters?: QueryParameters): Promise<DatabaseQueryResult>;

  /**
   * Commit the transaction
   */
  commit(): Promise<void>;

  /**
   * Rollback the transaction
   */
  rollback(): Promise<void>;

  /**
   * Create a savepoint
   */
  savepoint(name: string): Promise<void>;

  /**
   * Rollback to a savepoint
   */
  rollbackToSavepoint(name: string): Promise<void>;

  /**
   * Release a savepoint
   */
  releaseSavepoint(name: string): Promise<void>;
}

